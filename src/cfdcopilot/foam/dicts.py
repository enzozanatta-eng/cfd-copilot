"""Minimal writer for OpenFOAM dictionary files.

Python values map to OpenFOAM syntax:

* ``dict``            -> sub-dictionary ``{ ... }``
* ``list``/``tuple``  -> list ``( ... )``
* ``bool``            -> ``yes``/``no``
* ``Raw``             -> written verbatim (dimensions, uniform fields, macros)
* anything else       -> ``str(value)``
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  Generated by cfd-copilot. Edit the case spec, not this file.
\\*---------------------------------------------------------------------------*/
"""


class Raw(str):
    """A string written to the dictionary exactly as given."""


def _fmt_scalar(value: Any) -> str:
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, float):
        return f"{value:.10g}"
    return str(value)


def _fmt_list(items: list | tuple) -> str:
    return "(" + " ".join(_fmt_value(v, 0) for v in items) + ")"


def _fmt_value(value: Any, indent: int) -> str:
    if isinstance(value, dict):
        return "\n" + _fmt_dict(value, indent)
    if isinstance(value, (list, tuple)):
        return _fmt_list(value)
    return _fmt_scalar(value)


def _fmt_dict(d: dict[str, Any], indent: int) -> str:
    pad = "    " * indent
    lines = [pad + "{"]
    lines.append(_fmt_entries(d, indent + 1))
    lines.append(pad + "}")
    return "\n".join(lines)


def _fmt_entries(d: dict[str, Any], indent: int) -> str:
    pad = "    " * indent
    out = []
    for key, value in d.items():
        if isinstance(value, Raw) and key.startswith("#"):
            out.append(f"{pad}{value}")
        elif isinstance(value, dict):
            out.append(f"{pad}{key}\n{_fmt_dict(value, indent)}")
        else:
            out.append(f"{pad}{key:<16} {_fmt_value(value, indent)};")
    return "\n".join(out)


def foam_file(cls: str, obj: str, body: dict[str, Any], location: str | None = None) -> str:
    """Render a complete OpenFOAM file (header + FoamFile + body)."""
    header: dict[str, Any] = {"format": "ascii", "class": cls}
    if location:
        header["location"] = f'"{location}"'
    header["object"] = obj
    return (
        HEADER
        + "FoamFile\n"
        + _fmt_dict(header, 0)
        + "\n\n"
        + _fmt_entries(body, 0)
        + "\n"
    )


def write_foam_file(
    case_dir: Path, rel_path: str, cls: str, body: dict[str, Any]
) -> Path:
    path = Path(case_dir) / rel_path
    path.parent.mkdir(parents=True, exist_ok=True)
    location, obj = rel_path.rsplit("/", 1) if "/" in rel_path else (None, rel_path)
    path.write_text(foam_file(cls, obj, body, location))
    return path
